"""
Node Modules Finder - Scan directories for node_modules folders.
Lists parent project name, last access date, size, and provides
options to open in Finder or delete.
"""

import os
import shutil
import subprocess
import threading
import tkinter as tk
from datetime import datetime
from tkinter import filedialog, messagebox, ttk


class NodeModulesFinder:
    def __init__(self, root):
        self.root = root
        self.root.title("Node Modules Finder")
        self.root.geometry("1000x600")
        self.root.minsize(800, 400)

        self.results = []  # list of dicts with node_modules info
        self.scanning = False

        self._build_ui()

    def _build_ui(self):
        # Top bar - folder selection
        top_frame = ttk.Frame(self.root, padding=10)
        top_frame.pack(fill=tk.X)

        ttk.Label(top_frame, text="Scan folder:").pack(side=tk.LEFT)

        self.path_var = tk.StringVar(value=os.path.expanduser("~"))
        path_entry = ttk.Entry(top_frame, textvariable=self.path_var)
        path_entry.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=(8, 8))

        ttk.Button(top_frame, text="Browse...", command=self._browse).pack(side=tk.LEFT)
        self.scan_btn = ttk.Button(top_frame, text="Scan", command=self._start_scan)
        self.scan_btn.pack(side=tk.LEFT, padx=(8, 0))

        # Status bar
        status_frame = ttk.Frame(self.root, padding=(10, 0, 10, 4))
        status_frame.pack(fill=tk.X)

        self.status_var = tk.StringVar(value="Select a folder and press Scan.")
        ttk.Label(status_frame, textvariable=self.status_var, foreground="gray").pack(
            side=tk.LEFT
        )

        self.total_size_var = tk.StringVar(value="")
        ttk.Label(status_frame, textvariable=self.total_size_var, foreground="gray").pack(
            side=tk.RIGHT
        )

        # Table
        columns = ("project", "path", "size", "accessed", "actions")
        table_frame = ttk.Frame(self.root, padding=(10, 0, 10, 10))
        table_frame.pack(fill=tk.BOTH, expand=True)

        self.tree = ttk.Treeview(
            table_frame,
            columns=columns,
            show="headings",
            selectmode="extended",
        )

        self.tree.heading("project", text="Project", anchor=tk.W)
        self.tree.heading("path", text="Path", anchor=tk.W)
        self.tree.heading("size", text="Size", anchor=tk.W)
        self.tree.heading("accessed", text="Last Accessed", anchor=tk.W)
        self.tree.heading("actions", text="", anchor=tk.CENTER)

        self.tree.column("project", width=180, minwidth=120)
        self.tree.column("path", width=350, minwidth=200)
        self.tree.column("size", width=100, minwidth=80)
        self.tree.column("accessed", width=160, minwidth=120)
        self.tree.column("actions", width=80, minwidth=60)

        scrollbar = ttk.Scrollbar(table_frame, orient=tk.VERTICAL, command=self.tree.yview)
        self.tree.configure(yscrollcommand=scrollbar.set)

        self.tree.pack(side=tk.LEFT, fill=tk.BOTH, expand=True)
        scrollbar.pack(side=tk.RIGHT, fill=tk.Y)

        self.tree.bind("<Double-1>", self._on_double_click)

        # Bottom buttons
        bottom_frame = ttk.Frame(self.root, padding=10)
        bottom_frame.pack(fill=tk.X)

        ttk.Button(
            bottom_frame, text="Open in Finder", command=self._open_selected
        ).pack(side=tk.LEFT)

        ttk.Button(
            bottom_frame,
            text="Delete Selected",
            command=self._delete_selected,
        ).pack(side=tk.LEFT, padx=(8, 0))

        ttk.Button(
            bottom_frame,
            text="Delete All",
            command=self._delete_all,
        ).pack(side=tk.LEFT, padx=(8, 0))

        ttk.Button(bottom_frame, text="Select All", command=self._select_all).pack(
            side=tk.RIGHT
        )

    # -- Actions --

    def _browse(self):
        folder = filedialog.askdirectory(initialdir=self.path_var.get())
        if folder:
            self.path_var.set(folder)

    def _start_scan(self):
        if self.scanning:
            return
        scan_path = self.path_var.get()
        if not os.path.isdir(scan_path):
            messagebox.showerror("Error", "Selected path is not a valid directory.")
            return

        self.scanning = True
        self.scan_btn.configure(state=tk.DISABLED)
        self.tree.delete(*self.tree.get_children())
        self.results.clear()
        self.status_var.set("Scanning...")
        self.total_size_var.set("")

        thread = threading.Thread(target=self._scan, args=(scan_path,), daemon=True)
        thread.start()

    def _scan(self, scan_path):
        found = []
        try:
            for dirpath, dirnames, _ in os.walk(scan_path):
                if "node_modules" in dirnames:
                    nm_path = os.path.join(dirpath, "node_modules")
                    info = self._get_info(nm_path, dirpath)
                    if info:
                        found.append(info)
                    # Don't recurse into this node_modules
                    dirnames.remove("node_modules")
                # Skip hidden dirs and common non-project dirs
                dirnames[:] = [
                    d for d in dirnames if not d.startswith(".") and d != "__pycache__"
                ]
        except PermissionError:
            pass

        self.root.after(0, self._scan_done, found)

    def _get_info(self, nm_path, parent_path):
        try:
            stat = os.stat(nm_path)
            accessed = datetime.fromtimestamp(stat.st_atime).strftime("%Y-%m-%d %H:%M")
            size = self._dir_size(nm_path)
            project_name = os.path.basename(parent_path)
            return {
                "project": project_name,
                "path": parent_path,
                "nm_path": nm_path,
                "size_bytes": size,
                "size": self._format_size(size),
                "accessed": accessed,
            }
        except OSError:
            return None

    def _dir_size(self, path):
        total = 0
        try:
            for dirpath, _, filenames in os.walk(path):
                for f in filenames:
                    fp = os.path.join(dirpath, f)
                    try:
                        total += os.path.getsize(fp)
                    except OSError:
                        pass
        except PermissionError:
            pass
        return total

    @staticmethod
    def _format_size(size_bytes):
        for unit in ("B", "KB", "MB", "GB"):
            if size_bytes < 1024:
                return f"{size_bytes:.1f} {unit}"
            size_bytes /= 1024
        return f"{size_bytes:.1f} TB"

    def _scan_done(self, found):
        self.results = found
        self.scanning = False
        self.scan_btn.configure(state=tk.NORMAL)

        for item in found:
            self.tree.insert(
                "",
                tk.END,
                values=(
                    item["project"],
                    item["path"],
                    item["size"],
                    item["accessed"],
                    "Double-click to open",
                ),
            )

        total = sum(r["size_bytes"] for r in found)
        count = len(found)
        self.status_var.set(f"Found {count} node_modules folder{'s' if count != 1 else ''}.")
        self.total_size_var.set(f"Total: {self._format_size(total)}")

    def _on_double_click(self, event):
        region = self.tree.identify_region(event.x, event.y)
        if region != "cell":
            return
        item_id = self.tree.identify_row(event.y)
        if not item_id:
            return
        idx = self.tree.index(item_id)
        if idx < len(self.results):
            subprocess.Popen(["open", self.results[idx]["nm_path"]])

    def _open_selected(self):
        for item_id in self.tree.selection():
            idx = self.tree.index(item_id)
            if idx < len(self.results):
                subprocess.Popen(["open", self.results[idx]["path"]])

    def _select_all(self):
        self.tree.selection_set(self.tree.get_children())

    def _delete_selected(self):
        selected = self.tree.selection()
        if not selected:
            messagebox.showinfo("Info", "No items selected.")
            return

        count = len(selected)
        total = sum(
            self.results[self.tree.index(s)]["size_bytes"]
            for s in selected
            if self.tree.index(s) < len(self.results)
        )
        confirm = messagebox.askyesno(
            "Confirm Delete",
            f"Delete {count} node_modules folder{'s' if count != 1 else ''}?\n"
            f"This will free ~{self._format_size(total)}.\n\n"
            "This action cannot be undone.",
        )
        if not confirm:
            return

        self._do_delete(selected)

    def _delete_all(self):
        if not self.results:
            messagebox.showinfo("Info", "Nothing to delete.")
            return

        total = sum(r["size_bytes"] for r in self.results)
        confirm = messagebox.askyesno(
            "Confirm Delete All",
            f"Delete ALL {len(self.results)} node_modules folders?\n"
            f"This will free ~{self._format_size(total)}.\n\n"
            "This action cannot be undone.",
        )
        if not confirm:
            return

        self._do_delete(self.tree.get_children())

    def _do_delete(self, item_ids):
        # Collect indices before deletion (indices shift as we remove)
        indices = sorted(
            [self.tree.index(i) for i in item_ids if self.tree.index(i) < len(self.results)],
            reverse=True,
        )

        errors = []
        freed = 0
        for idx in indices:
            info = self.results[idx]
            try:
                shutil.rmtree(info["nm_path"])
                freed += info["size_bytes"]
                self.results.pop(idx)
            except Exception as e:
                errors.append(f"{info['project']}: {e}")

        # Rebuild tree
        self.tree.delete(*self.tree.get_children())
        for item in self.results:
            self.tree.insert(
                "",
                tk.END,
                values=(
                    item["project"],
                    item["path"],
                    item["size"],
                    item["accessed"],
                    "Double-click to open",
                ),
            )

        total = sum(r["size_bytes"] for r in self.results)
        count = len(self.results)
        self.status_var.set(
            f"Deleted! Freed {self._format_size(freed)}. "
            f"{count} folder{'s' if count != 1 else ''} remaining."
        )
        self.total_size_var.set(f"Total: {self._format_size(total)}" if self.results else "")

        if errors:
            messagebox.showwarning(
                "Some deletions failed",
                "\n".join(errors),
            )


def main():
    root = tk.Tk()
    NodeModulesFinder(root)
    root.mainloop()


if __name__ == "__main__":
    main()
